describe('Size enum order regression protection', () => {
  test('sizeConfig rejects schemas with non-canonical size order', () => {
    // Test that schema with sizes in wrong order is rejected
    const schemaWithWrongSizeOrder = JSON.stringify({
      required: ['id', 'Name', 'Size'],
      properties: {
        Status: {
          enum: ['AVAILABLE', 'ADOPTED', 'PENDING'],
          'x-terminal-statuses': ['ADOPTED']
        },
        Size: {
          enum: ['X-Large', 'Small', 'UNKNOWN', 'Medium', 'Large'] // Wrong order
        }
      }
    }, null, 2);

    // Should throw an error because size order doesn't match canonical order
    expect(() => generateAllArtifacts(schemaWithWrongSizeOrder)).toThrow(
      'Schema Size enum order does not match expected SIZE_ORDER'
    );
  });

  test('sizeConfig accepts schemas with canonical size order', () => {
    // Test with correct canonical size order
    const schemaWithCorrectSizeOrder = JSON.stringify({
      required: ['id', 'Name', 'Size'],
      properties: {
        Status: {
          enum: ['AVAILABLE', 'ADOPTED', 'PENDING'],
          'x-terminal-statuses': ['ADOPTED']
        },
        Size: {
          enum: ['Small', 'Medium', 'Large', 'X-Large', 'UNKNOWN'] // Correct canonical order
        }
      }
    }, null, 2);

    const artifacts = generateAllArtifacts(schemaWithCorrectSizeOrder);

    // Should generate successfully
    expect(artifacts.sizeConfig).toContain('SIZE_ORDER = [');
    expect(artifacts.sizeConfig).toContain("'Small'");
    expect(artifacts.sizeConfig).toContain("'Medium'");
    expect(artifacts.sizeConfig).toContain("'Large'");
    expect(artifacts.sizeConfig).toContain("'X-Large'");
    expect(artifacts.sizeConfig).toContain("'UNKNOWN'");

    // Verify the canonical order is preserved
    const sizeOrderMatch = artifacts.sizeConfig.match(/SIZE_ORDER = \[([^\]]+)\]/);
    expect(sizeOrderMatch).toBeTruthy();

    const sizeOrderArray = sizeOrderMatch[1]
      .split(',')
      .map(s => s.trim().replace(/'/g, ''))
      .filter(s => s.length > 0);

    expect(sizeOrderArray).toEqual(['Small', 'Medium', 'Large', 'X-Large', 'UNKNOWN']);
  });

  test('checksum validation catches manually edited size configs', () => {
    // This test ensures that if someone manually edits a generated size config,
    // it would be caught by the checksum validation

    // Generate artifacts with the correct schema
    const correctArtifacts = generateAllArtifacts(mockSchemaContent);
    const correctChecksum = generateSchemaChecksum(mockSchemaContent);

    // Verify the generated config has the correct checksum
    expect(correctArtifacts.sizeConfig).toContain(`* Schema checksum: ${correctChecksum}`);

    // Simulate someone manually editing the sizeConfig to change the checksum
    const manuallyEditedSizeConfig = correctArtifacts.sizeConfig.replace(
      `* Schema checksum: ${correctChecksum}`,
      '* Schema checksum: manually-edited'
    );

    // The manually edited version wouldn't contain the correct checksum
    expect(manuallyEditedSizeConfig).not.toContain(`* Schema checksum: ${correctChecksum}`);

    // And would contain the wrong checksum
    expect(manuallyEditedSizeConfig).toContain('* Schema checksum: manually-edited');
  });
});

describe('New status detection', () => {
  test('generator includes new status in all outputs when schema adds status', () => {
    const schemaWithNewStatus = JSON.stringify({
      required: ['id', 'Name', 'Status'],
      properties: {
        Status: {
          enum: ['AVAILABLE', 'ADOPTED', 'PENDING', 'HOLD', 'NEW_STATUS'], // Added NEW_STATUS
          'x-terminal-statuses': ['ADOPTED']
        },
        Size: {
          enum: ['Small', 'Medium', 'Large', 'X-Large', 'UNKNOWN']
        }
      }
    }, null, 2);

    const artifacts = generateAllArtifacts(schemaWithNewStatus);

    // Status mapping should include NEW_STATUS
    expect(artifacts.statusMapping).toContain('NEW_STATUS');
    expect(artifacts.statusMapping).toContain("'NEW_STATUS'");
    expect(artifacts.statusMapping).toContain('New_status'); // Display text
    expect(artifacts.statusMapping).toContain('status-new_status'); // CSS class

    // Verify all original statuses are still present
    expect(artifacts.statusMapping).toContain('AVAILABLE');
    expect(artifacts.statusMapping).toContain('ADOPTED');
    expect(artifacts.statusMapping).toContain('PENDING');
    expect(artifacts.statusMapping).toContain('HOLD');

    // Verify enumerateStatuses includes the new status
    const schema = JSON.parse(schemaWithNewStatus);
    const statuses = enumerateStatuses(schema);
    expect(statuses).toContain('NEW_STATUS');
    expect(statuses.length).toBe(5);
  });

  test('checksum changes when new status is added', () => {
    const originalChecksum = generateSchemaChecksum(mockSchemaContent);

    const schemaWithNewStatus = JSON.stringify({
      required: ['id', 'Name', 'Status'],
      properties: {
        Status: {
          enum: ['AVAILABLE', 'ADOPTED', 'PENDING', 'NEW_STATUS'],
          'x-terminal-statuses': ['ADOPTED']
        },
        Size: {
          enum: ['Small', 'Medium', 'Large', 'X-Large', 'UNKNOWN']
        }
      }
    }, null, 2);

    const newChecksum = generateSchemaChecksum(schemaWithNewStatus);

    expect(originalChecksum).not.toBe(newChecksum);
  });
});
